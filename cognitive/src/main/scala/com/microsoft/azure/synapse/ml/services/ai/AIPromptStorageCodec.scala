package com.microsoft.azure.synapse.ml.services.ai

import org.apache.spark.ml.linalg.SQLDataTypes
import org.apache.spark.sql.DataFrame
import org.apache.spark.sql.types._
import spray.json._

/** The on-disk schema is deliberately independent of Spark's arbitrary UDT deserializer. */
private[ai] object AIPromptStorageCodec {
  private val VectorTag = "aiprompt-vector-v1"
  private val PrimitiveTypes = Seq(StringType, BinaryType, BooleanType, ByteType, ShortType,
    IntegerType, LongType, FloatType, DoubleType, DateType, TimestampType, TimestampNTZType)
    .map(t => t.typeName -> t).toMap
  // Delta strips these source-column behaviors when reading a materialized snapshot.
  private val SourceMetadataKeys = Seq(
    "__autoGeneratedAlias", "__metadata_col", "__supports_qualified_star", "__qualified_access_only",
    "__file_source_metadata_col", "__file_source_constant_metadata_col", "__file_source_generated_metadata_col",
    "delta.generationExpression", "delta.identity.allowExplicitInsert", "delta.identity.highWaterMark",
    "delta.identity.start", "delta.identity.step")

  def durable(dataType: DataType): DataType = dataType match {
    case s: StructType => StructType(s.fields.map { field =>
      val metadata = new MetadataBuilder().withMetadata(field.metadata)
      SourceMetadataKeys.foreach(metadata.remove)
      field.copy(dataType = durable(field.dataType), nullable = true, metadata = metadata.build())
    })
    case ArrayType(t, _) => ArrayType(durable(t), containsNull = true)
    case MapType(k, v, _) => MapType(durable(k), durable(v), valueContainsNull = true)
    case other => other
  }

  def nullable(dataType: DataType): DataType = AIValueCodec.nullable(dataType)

  def validate(schema: StructType): Unit = {
    validateType(schema, 0)
    decodeType(parseSchemaJson(encodeType(schema).compactPrint))
  }

  private def parseSchemaJson(json: String): JsValue = try {
    AIJson.parse(json)
  } catch {
    case _: IllegalArgumentException =>
      throw new IllegalArgumentException(
        "AIPrompt durable schema contains invalid JSON or exceeds supported parsing limits (including metadata).")
  }


  def validateFieldResolution(dataType: DataType): Unit = dataType match {
    case s: StructType =>
      AIColumnPlan.distinct(s.fieldNames.toSeq, "durable fields")
      s.fields.foreach(field => validateFieldResolution(field.dataType))
    case ArrayType(t, _) => validateFieldResolution(t)
    case MapType(k, v, _) => validateFieldResolution(k); validateFieldResolution(v)
    case _ =>
  }

  private def validateStruct(schema: StructType, depth: Int): Unit = {
    schema.fields.foreach { field =>
      require(field.name.nonEmpty && !field.name.exists(" ,;{}()\n\t=".contains(_)),
        "AIPrompt durable storage requires Delta-compatible column names (including nested fields).")
      // Stored structs wrap each field type in a struct array and field object.
      validateType(field.dataType, depth + 3)
    }
    require(schema.fieldNames.map(_.toLowerCase(java.util.Locale.ROOT)).distinct.length == schema.length,
      "AIPrompt durable storage does not support case-insensitive duplicate column names.")
  }

  private def validateType(dataType: DataType, depth: Int): Unit = {
    require(depth <= AIJson.MaxDepth, "AIPrompt durable schema exceeds the supported depth.")
    dataType match {
      case s: StructType =>
        require(depth == 0 || s.nonEmpty, "AIPrompt durable storage does not support nested empty structs.")
        validateStruct(s, depth)
      case ArrayType(t, _) => validateType(t, depth + 1)
      case MapType(k, v, _) => validateType(k, depth + 1); validateType(v, depth + 1)
      case other => validateLeaf(other)
    }
  }

  private def validateLeaf(dataType: DataType): Unit = dataType match {
    case t if t == SQLDataTypes.VectorType =>
    case _: UserDefinedType[_] =>
      throw new IllegalArgumentException("AIPrompt durable storage supports only the Spark ML vector UDT.")
    case decimal: DecimalType =>
      require(decimal.scale >= 0, "AIPrompt durable storage supports only nonnegative decimal scales.")
    case t if PrimitiveTypes.values.toSeq.contains(t) =>
    case _ => throw new IllegalArgumentException("Unsupported SQL type for AIPrompt durable storage.")
  }

  def physical(dataType: DataType): DataType = dataType match {
    case t if t == SQLDataTypes.VectorType => AIValueCodec.VectorStorage
    case s: StructType => StructType(s.fields.map(f => f.copy(dataType = physical(f.dataType), nullable = true)))
    case ArrayType(t, _) => ArrayType(physical(t), containsNull = true)
    case MapType(k, v, _) => MapType(physical(k), physical(v), valueContainsNull = true)
    case other => other
  }

  def encode(frame: DataFrame, schema: StructType): DataFrame = convertFrame(frame, schema, encode = true)

  def decode(frame: DataFrame, schema: StructType): DataFrame = convertFrame(frame, schema, encode = false)

  private def convertFrame(frame: DataFrame, schema: StructType, encode: Boolean): DataFrame = {
    val target = if (encode) physical(schema).asInstanceOf[StructType] else schema
    val columns = schema.fields.map { field =>
      val column = AIColumnPlan.column(field.name)
      val sourceField = frame.schema(field.name)
      val resultField = target(field.name)
      val resultType = resultField.dataType
      val converted = if (AIValueCodec.containsVector(field.dataType)) {
        AIValueCodec.convertColumn(column, field.dataType, field.nullable, encode)
      } else if (sourceField.dataType == resultType) column else column.cast(resultType)
      converted.as(field.name, field.metadata)
    }
    AIValueCodec.reconcileSchema(frame.select(columns: _*), target)
  }

  def schemaJson(schema: StructType): String = {
    validate(schema)
    encodeType(nullable(schema)).compactPrint
  }

  private def encodeType(dataType: DataType): JsValue = dataType match {
    case t if t == SQLDataTypes.VectorType => JsString(VectorTag)
    case s: StructType => JsObject("struct" -> JsArray(s.fields.map { f =>
      JsObject("name" -> JsString(f.name), "type" -> encodeType(f.dataType),
        "metadata" -> parseSchemaJson(f.metadata.json))
    }.toVector))
    case ArrayType(t, _) => JsObject("array" -> encodeType(t))
    case MapType(k, v, _) => JsObject("key" -> encodeType(k), "value" -> encodeType(v))
    case d: DecimalType => JsObject("precision" -> JsNumber(d.precision), "scale" -> JsNumber(d.scale))
    case other => JsString(other.typeName)
  }

  def readSchema(json: String): StructType = {
    val schema = decodeType(parseSchemaJson(json)) match {
      case value: StructType => value
      case _ => throw new IllegalArgumentException("AIPrompt stored schema must be a struct.")
    }
    validate(schema)
    schema
  }

  private def decodeType(json: JsValue): DataType = json match {
    case JsString(VectorTag) => SQLDataTypes.VectorType
    case JsString(name) => PrimitiveTypes.getOrElse(name,
      throw new IllegalArgumentException("Unknown AIPrompt stored type; arbitrary UDTs are not loaded."))
    case JsObject(fields) => decodeContainer(fields)
    case _ => throw new IllegalArgumentException("Invalid or unsupported AIPrompt stored schema.")
  }

  private def decodeContainer(fields: Map[String, JsValue]): DataType = fields.toSeq.sortBy(_._1) match {
    case Seq(("struct", JsArray(elements))) =>
      StructType(elements.map(decodeField))
    case Seq(("array", value)) => ArrayType(decodeType(value), true)
    case Seq(("key", key), ("value", value)) => MapType(decodeType(key), decodeType(value), true)
    case Seq(("precision", JsNumber(precision)), ("scale", JsNumber(scale))) =>
      require(precision.isValidInt && scale.isValidInt, "Invalid AIPrompt stored decimal type.")
      try DecimalType(precision.toInt, scale.toInt) catch {
        case _: IllegalArgumentException | _: ArithmeticException |
             _: org.apache.spark.sql.AnalysisException | _: org.apache.spark.SparkException =>
          throw new IllegalArgumentException("Invalid AIPrompt stored decimal type.")
      }
    case _ => throw new IllegalArgumentException("Invalid or unsupported AIPrompt stored schema.")
  }

  private def decodeField(json: JsValue): StructField = json match {
    case JsObject(fields) if fields.keySet == Set("name", "type", "metadata") =>
      (fields("name"), fields("metadata")) match {
        case (JsString(name), metadata: JsObject) =>
          val decoded = try Metadata.fromJson(metadata.compactPrint) catch {
            case _: ClassCastException | _: IllegalArgumentException =>
              throw new IllegalArgumentException("Invalid AIPrompt stored field metadata.")
            case error: org.apache.spark.SparkThrowable if Set(
              "_LEGACY_ERROR_TEMP_2120", "_LEGACY_ERROR_TEMP_2121")(error.getErrorClass) =>
              throw new IllegalArgumentException("Invalid AIPrompt stored field metadata.")
          }
          require(AIJson.parse(decoded.json) == metadata, "Invalid AIPrompt stored field metadata.")
          StructField(name, decodeType(fields("type")), nullable = true, decoded)
        case _ => throw new IllegalArgumentException("Invalid AIPrompt stored schema field.")
      }
    case _ => throw new IllegalArgumentException("Invalid AIPrompt stored schema field.")
  }
}
